// Builds the exact JavaScript to pass to the Figma MCP's use_figma tool. The skill never hand-writes
// Plugin API code for token data: it runs `token-parity figma-script ...` and passes the output unchanged.
import { tpBuildExport, tpChecksum, tpCyrb53, tpExportVariables, tpF32, tpPushChanges } from "./figma-bridge.js";
import type { FigmaChangeSet } from "./types.js";

type Fn = (...args: never[]) => unknown;
const HELPERS: Fn[] = [tpCyrb53, tpChecksum, tpF32, tpBuildExport];

/**
 * Each function is defined under the name the running code gives it (`fn.name`), not the source name: in a
 * minified bundle `tpChecksum` may be `U`, and the other helpers' bodies call it as `U`.
 */
function define(fns: Fn[]): string {
  return fns
    .map((fn) => {
      if (!/^[A-Za-z_$][\w$]*$/.test(fn.name)) throw new Error(`figma-script: helper has no usable name (${fn.name || "anonymous"})`);
      return `const ${fn.name} = ${fn.toString()};`;
    })
    .join("\n");
}

const HEADER = "// Generated by token-parity. Pass to use_figma unchanged; it verifies its own payload.";

/** @param known checksum of the saved export; the plugin answers `unchanged` instead of resending it. */
export function exportScript(known: string | null = null): string {
  return `${HEADER}\n${define([...HELPERS, tpExportVariables])}\nreturn await ${tpExportVariables.name}(figma, ${JSON.stringify(known)});\n`;
}

export function pushScript(changes: FigmaChangeSet): string {
  const json = JSON.stringify(changes);
  return `${HEADER}\n${define([...HELPERS, tpPushChanges])}\nconst CHANGES = ${json};\nreturn await ${tpPushChanges.name}(figma, CHANGES, ${JSON.stringify(tpChecksum(json))});\n`;
}

/** Checksum of a JSON document regardless of formatting: hash of JSON.stringify(JSON.parse(text)). */
export function jsonChecksum(text: string): string {
  return tpChecksum(JSON.stringify(JSON.parse(text)));
}
