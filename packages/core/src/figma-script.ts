// Builds the exact JavaScript to pass to the Figma MCP's use_figma tool. The skill never hand-writes
// Plugin API code for token data: it runs `token-parity figma-script ...` and passes the output unchanged.
import { tpBuildExport, tpChecksum, tpCyrb53, tpExportVariables, tpPushChanges } from "./figma-bridge.js";
import type { FigmaChangeSet } from "./types.js";

// Explicit names: the code references these identifiers, whatever a bundler calls the functions.
const HELPERS: Array<[string, (...args: never[]) => unknown]> = [
  ["tpCyrb53", tpCyrb53],
  ["tpChecksum", tpChecksum],
  ["tpBuildExport", tpBuildExport],
];

function define(fns: Array<[string, (...args: never[]) => unknown]>): string {
  return fns.map(([name, fn]) => `const ${name} = ${fn.toString()};`).join("\n");
}

const HEADER = "// Generated by token-parity. Pass to use_figma unchanged; it verifies its own payload.";

export function exportScript(): string {
  return `${HEADER}\n${define([...HELPERS, ["tpExportVariables", tpExportVariables]])}\nreturn await tpExportVariables(figma);\n`;
}

export function pushScript(changes: FigmaChangeSet): string {
  const json = JSON.stringify(changes);
  return `${HEADER}\n${define([...HELPERS, ["tpPushChanges", tpPushChanges]])}\nconst CHANGES = ${json};\nreturn await tpPushChanges(figma, CHANGES, ${JSON.stringify(tpChecksum(json))});\n`;
}

/** Checksum of a JSON document regardless of formatting: hash of JSON.stringify(JSON.parse(text)). */
export function jsonChecksum(text: string): string {
  return tpChecksum(JSON.stringify(JSON.parse(text)));
}
